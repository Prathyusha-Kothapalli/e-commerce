const ReviewsEngine = {
  getReviewsForDress(dressId) { return VerifiedReviewsDatabase.filter(r => r.dressId === Number(dressId)); },
  getAverageRating(dressId) {
    const revs = this.getReviewsForDress(dressId);
    if (revs.length === 0) return 5.0;
    return (revs.reduce((sum, r) => sum + r.rating, 0) / revs.length).toFixed(1);
  }
};

